import { NORMALIZATION_META } from "@scrivr/core";
import { closeHistory, EditorState, Plugin, PluginKey, Transaction } from "@scrivr/core/pm";

import {
  getAction,
  suggestionIntent,
  hasAction,
  setAction,
  TrackChangesAction,
} from "../actions";
import { ChangeSet } from "../ChangeSet";
import { findChanges } from "../findChanges";
import { fromCollaborator, gestureRefusal, trackChanges, untracked } from "./trackChanges";
import { fixInconsistentChanges } from "../lib/fixInconsistentChanges";
import { TrackChangesOptions, TrackChangesStatus } from "../types";
import { planReviewIn } from "../reviewChanges";
import type { TrackingResult } from "../types";
import { reportedTracking, trFromHistory } from "./transactionProcessing";
import { closeDependentCreations, composeGestureRecords } from "./composition";
import { fixAndSetSelectionAfterTracking, type ReplayedSelection } from "./fixAndSetSelectionAfterTracking";
import { normalizeMoveShadows } from "./moveIdentity";
import { updateChangesStatus } from "./updateChangesStatus";
import { cutOf, lastCutKey, markCutMoved, moveIdForPaste, rememberCut } from "../lib/cutAndPaste";

import type { ReviewOutcome } from "../reviewPlan";

/**
 * What the plugin knows. A host reads this off `trackChangesPluginKey` — the
 * outcomes especially, since a refusal is the one a host must act on — so it
 * needs a name it can write down.
 */
export interface TrackChangesState {
  /** Outcome of the most recent review decision, applied or refused. */
  lastReview: ReviewOutcome | null;
  /**
   * Outcome of the most recent tracked gesture; `refused` needs host action.
   * Undo and redo clear it, since they replace what that gesture produced.
   */
  lastTracking: TrackingResult | null;
  status: TrackChangesStatus;
  changeSet: ChangeSet;
  userID: string;
  canAcceptReject: boolean;
}

type TrackChangesPluginState = TrackChangesState & {
  /** The outcome that speaks for this dispatch so far: see `reportedTracking`. */
  trackingInDispatch: TrackingResult | null;
};

export const trackChangesPluginKey = new PluginKey<TrackChangesState>(
  "track-changes",
);

export const trackChangesPlugin = (options: TrackChangesOptions) => {
  const { userID, skipTrsWithMetas = [], canAcceptReject = true, onRefused } = options;

  return new Plugin<TrackChangesPluginState>({
    key: trackChangesPluginKey,
    // An edit that could not be recorded as a suggestion is stopped rather than
    // let through unrecorded: someone suggesting must not change the text directly.
    // Viewing snapshots, only edits nobody here authored (sync, load, normalization) go through.
    filterTransaction(tr, state) {
      const pluginState = trackChangesPluginKey.getState(state);
      if (!pluginState || tr.getMeta("origin") === trackChangesPluginKey) return true;
      if (pluginState.status === TrackChangesStatus.viewSnapshots) return untracked(tr, skipTrsWithMetas);
      const suggesting = pluginState.status === TrackChangesStatus.enabled || !!suggestionIntent(tr);
      if (!suggesting || getAction(tr, TrackChangesAction.setChangeStatuses)) return true;
      const refusal = gestureRefusal(tr, state, skipTrsWithMetas);
      if (!refusal) return true;
      onRefused?.(refusal);
      return false;
    },
    appendTransaction(trs, oldState, newState) {
      const pluginState = trackChangesPluginKey.getState(newState);
      if (!pluginState) return null;
      const shouldSkipTracking = pluginState.status === TrackChangesStatus.disabled;

      if (shouldSkipTracking && !pluginState.canAcceptReject && !trs.some(suggestionIntent)) {
        return null;
      }

      const { userID, changeSet } = pluginState;
      let createdTr: Transaction = newState.tr,
        docChanged = false;
      const replayedSelection: ReplayedSelection = { restamps: new Map() };

      trs.forEach((tx, i) => {
        // Skip transactions generated by this plugin to prevent re-tracking
        // already-tracked steps. Without this guard, the tracking transaction
        // re-enters appendTransaction and gets tracked again, causing a
        // duplicate-node feedback loop that crashes the browser on paste.
        if (tx.getMeta("origin") === trackChangesPluginKey) {
          docChanged = docChanged || tx.docChanged;
          return;
        }

        const collabRebased = tx.getMeta("rebase");
        if (collabRebased !== undefined) {
          setAction(createdTr, TrackChangesAction.refreshChanges, true);
          docChanged = true;
          return;
        }

        if (fromCollaborator(tx)) {
          setAction(createdTr, TrackChangesAction.refreshChanges, true);
          docChanged = true;
          return;
        }

        const setsChangeStatus = getAction(
          tx,
          TrackChangesAction.setChangeStatuses,
        );
        if (setsChangeStatus) {
          // Whether the decision may go ahead is the shared rule's to answer,
          // not this gate's — and a refusal is still an outcome, so it is
          // reported rather than dropped.
          const plan = planReviewIn(oldState, setsChangeStatus);
          const review =
            plan.status === "blocked" ? plan : updateChangesStatus(createdTr, changeSet, plan, userID);
          setAction(createdTr, TrackChangesAction.reviewResult, review);
          // A decision is its own undo step. History never opens a group for an
          // appended transaction by itself, so it would join the preceding edit.
          closeHistory(createdTr);
          docChanged = true;
        } else if (!shouldSkipTracking || suggestionIntent(tx)) {
          const authorID = suggestionIntent(tx)?.authorID ?? userID;
          const uiEvent = tx.getMeta("uiEvent");
          const lastCut = lastCutKey.getState(newState) ?? null;
          const pastedMove = uiEvent === "paste" && lastCut ? moveIdForPaste(tx, lastCut, createdTr.doc, authorID) : null;
          // Each transaction is recorded from where it started, as it was judged before it applied.
          const startState = i === 0 ? oldState : EditorState.create({ doc: tx.before, selection: trs[i - 1]!.selection });
          const outcome = trackChanges(
            tx, createdTr, startState, authorID, skipTrsWithMetas, replayedSelection, pastedMove ?? undefined,
          );
          if (outcome.kind === "tracked") {
            createdTr = outcome.tr;
            if (uiEvent === "cut") {
              rememberCut(createdTr, cutOf(tx, changeSet, createdTr.doc, authorID));
            } else if (pastedMove && lastCut) {
              markCutMoved(createdTr, lastCut, pastedMove);
            }
          }
          // A refusal is the outcome a host has to act on, so it outranks a
          // sibling success in the same round: one dispatch can carry several
          // transactions, and the last of them must not speak for all.
          if (outcome.kind !== "skipped") {
            setAction(
              createdTr,
              TrackChangesAction.trackingResult,
              reportedTracking(
                getAction(createdTr, TrackChangesAction.trackingResult),
                outcome.result,
              ),
            );
          }
        }
        docChanged = docChanged || tx.docChanged;
      });
      if (createdTr.docChanged) {
        // Order matters: composition reads which creation encloses a record,
        // which only holds once a shadow's duplicated records are gone.
        normalizeMoveShadows(createdTr);
        composeGestureRecords(createdTr, oldState.doc);
        closeDependentCreations(createdTr);
        fixAndSetSelectionAfterTracking(createdTr, newState.selection, replayedSelection);
      }
      // Read from the document this round produced, not the change set from
      // before it: a split made now has to be repaired now, or its second
      // piece is invisible to review until something else happens.
      const current = docChanged || createdTr.docChanged
        ? findChanges(EditorState.create({ doc: createdTr.doc }))
        : pluginState.changeSet;
      const changed =
        current.hasInconsistentData &&
        fixInconsistentChanges(current, userID, createdTr, oldState.schema);
      if (docChanged || createdTr.docChanged || changed) {
        createdTr.setMeta("origin", trackChangesPluginKey);
        // Recording a change is bookkeeping, not authoring: the copy a pending
        // move leaves behind shares the moved block's id by design, and must
        // not be re-keyed as though someone had pasted it.
        createdTr.setMeta(NORMALIZATION_META, true);
        return setAction(createdTr, TrackChangesAction.refreshChanges, true);
      }
      return null;
    },
    state: {
      init: (_config, state: EditorState) => {
        return {
          lastReview: null,
          lastTracking: null,
          trackingInDispatch: null,
          status: options.initialStatus || TrackChangesStatus.enabled,
          userID,
          changeSet: findChanges(state),
          canAcceptReject,
        };
      },
      apply: (tr, previous, _oldState, newState) => {
        // ProseMirror applies a root once, then tags every appended transaction
        // with that root. Reset the accumulator here, including selection-only
        // roots, so append rounds share an outcome without leaking into the
        // next dispatch. Keep the last published outcome until new work arrives.
        let pluginState = !tr.getMeta("appendedTransaction") && previous.trackingInDispatch
          ? { ...previous, trackingInDispatch: null }
          : previous;
        if (trFromHistory(tr)) pluginState = { ...pluginState, lastTracking: null, trackingInDispatch: null };
        if (!tr.docChanged && !hasAction(tr)) {
          return pluginState;
        }
        const review = getAction(tr, TrackChangesAction.reviewResult);
        const tracking = getAction(tr, TrackChangesAction.trackingResult);
        if (tracking) {
          const result = reportedTracking(pluginState.trackingInDispatch ?? undefined, tracking);
          pluginState = { ...pluginState, lastTracking: result, trackingInDispatch: result };
        }
        if (review || tracking) return {
          ...pluginState,
          ...(review ? { lastReview: review } : {}),
          changeSet: findChanges(newState),
        };
        const setUserID = getAction(tr, TrackChangesAction.setUserID);
        const setStatus = getAction(tr, TrackChangesAction.setPluginStatus);
        if (setUserID) {
          return { ...pluginState, userID: setUserID };
        } else if (setStatus) {
          return {
            ...pluginState,
            status: setStatus,
            changeSet: findChanges(newState),
          };
        } else if (pluginState.status === TrackChangesStatus.disabled) {
          return { ...pluginState, changeSet: findChanges(newState) };
        }
        const { changeSet, ...rest } = pluginState;
        let nextChangeSet = changeSet;

        if (
          getAction(tr, TrackChangesAction.refreshChanges) ||
          trFromHistory(tr)
        ) {
          nextChangeSet = findChanges(newState);
        }

        return {
          changeSet: nextChangeSet,
          ...rest,
        };
      },
    },
  });
};
